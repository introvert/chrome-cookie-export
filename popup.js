"use strict";

const $ = (id) => document.getElementById(id);

const state = {
  tab: null,
  url: null,
  storeId: undefined,
  cookies: [],
};

// ---------- cookie collection ----------

async function getStoreIdForTab(tabId) {
  // Needed so incognito tabs read from the incognito cookie store.
  const stores = await chrome.cookies.getAllCookieStores();
  const store = stores.find((s) => s.tabIds.includes(tabId));
  return store ? store.id : undefined;
}

function cookieKey(c) {
  const pk = c.partitionKey ? JSON.stringify(c.partitionKey) : "";
  return `${c.name}\u0000${c.domain}\u0000${c.path}\u0000${c.storeId}\u0000${pk}`;
}

async function safeGetAll(details) {
  try {
    return await chrome.cookies.getAll(details);
  } catch (e) {
    // e.g. partitionKey unsupported on older Chrome versions
    return [];
  }
}

async function collectCookies(url, storeId, wholeDomain) {
  const base = storeId ? { storeId } : {};
  const { hostname, origin } = new URL(url);
  const queries = [
    // Every cookie the browser would send to this URL (includes parent-domain cookies).
    { ...base, url },
    // Partitioned (CHIPS) cookies set under this top-level site.
    { ...base, url, partitionKey: { topLevelSite: origin } },
  ];

  if (wholeDomain) {
    const domain = hostname.replace(/^www\./, "");
    // All cookies for this domain and its subdomains, any path.
    queries.push({ ...base, domain });
    queries.push({ ...base, domain, partitionKey: { topLevelSite: origin } });
  }

  const results = await Promise.all(queries.map(safeGetAll));
  const map = new Map();
  for (const list of results) {
    for (const c of list) map.set(cookieKey(c), c);
  }
  return [...map.values()].sort(
    (a, b) =>
      a.domain.localeCompare(b.domain) ||
      a.path.localeCompare(b.path) ||
      a.name.localeCompare(b.name)
  );
}

// ---------- formatters ----------

function toJSON(cookies) {
  return JSON.stringify(cookies, null, 2);
}

function toNetscape(cookies) {
  const lines = [
    "# Netscape HTTP Cookie File",
    "# https://curl.se/docs/http-cookies.html",
    "# This file was generated by Cookie Export. Edit at your own risk.",
    "",
  ];
  for (const c of cookies) {
    // Netscape format: host-only cookies have no leading dot and FALSE flag.
    let domain = c.domain;
    const includeSub = !c.hostOnly;
    if (includeSub && !domain.startsWith(".")) domain = "." + domain;
    if (!includeSub && domain.startsWith(".")) domain = domain.slice(1);
    if (c.httpOnly) domain = "#HttpOnly_" + domain;

    lines.push(
      [
        domain,
        includeSub ? "TRUE" : "FALSE",
        c.path,
        c.secure ? "TRUE" : "FALSE",
        c.session || !c.expirationDate ? 0 : Math.floor(c.expirationDate),
        c.name,
        c.value,
      ].join("\t")
    );
  }
  return lines.join("\n") + "\n";
}

function toHeader(cookies) {
  // Browsers send longer (more specific) paths first.
  return [...cookies]
    .sort((a, b) => b.path.length - a.path.length).map((c) => `${c.name}=${c.value}`).join("; ");
}

const FORMATS = {
  json: { fn: toJSON, ext: "json", mime: "application/json" },
  netscape: { fn: toNetscape, ext: "txt", mime: "text/plain" },
  header: { fn: toHeader, ext: "txt", mime: "text/plain" },
};

// ---------- UI ----------

function setStatus(msg, isError = false) {
  const el = $("status");
  el.textContent = msg;
  el.classList.toggle("error", isError);
  if (msg && !isError) {
    clearTimeout(setStatus.t);
    setStatus.t = setTimeout(() => (el.textContent = ""), 2500);
  }
}

function render() {
  const fmt = FORMATS[$("format").value];
  const text = fmt.fn(state.cookies);
  $("output").value = text;
  const n = state.cookies.length;
  $("count").textContent = `${n} cookie${n === 1 ? "" : "s"}`;
  $("copy").disabled = $("download").disabled = n === 0;
}

async function refresh() {
  try {
    state.cookies = await collectCookies(
      state.url,
      state.storeId,
      $("wholeDomain").checked
    );
    render();
  } catch (e) {
    setStatus(`Failed to read cookies: ${e.message}`, true);
  }
}

function savePrefs() {
  try {
    localStorage.setItem(
      "prefs",
      JSON.stringify({
        format: $("format").value,
        wholeDomain: $("wholeDomain").checked,
      })
    );
  } catch (_) {}
}

function loadPrefs() {
  try {
    const p = JSON.parse(localStorage.getItem("prefs") || "{}");
    if (p.format && FORMATS[p.format]) $("format").value = p.format;
    if (typeof p.wholeDomain === "boolean") $("wholeDomain").checked = p.wholeDomain;
  } catch (_) {}
}

async function copyOutput() {
  try {
    await navigator.clipboard.writeText($("output").value);
    setStatus("Copied to clipboard");
  } catch (e) {
    $("output").select();
    document.execCommand("copy");
    setStatus("Copied to clipboard");
  }
}

function downloadOutput() {
  const key = $("format").value;
  const fmt = FORMATS[key];
  const host = new URL(state.url).hostname;
  const stamp = new Date().toISOString().replace(/[:.]/g, "-").slice(0, 19);
  const suffix = key === "netscape" ? "cookies" : key === "header" ? "cookie-header" : "cookies";
  const filename = `${host}_${suffix}_${stamp}.${fmt.ext}`;

  const blob = new Blob([$("output").value], { type: fmt.mime });
  const href = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = href;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(href), 1000);
  setStatus(`Saved ${filename}`);
}

async function init() {
  loadPrefs();
  $("format").addEventListener("change", () => { savePrefs(); render(); });
  $("wholeDomain").addEventListener("change", () => { savePrefs(); refresh(); });
  $("copy").addEventListener("click", copyOutput);
  $("download").addEventListener("click", downloadOutput);

  const [tab] = await chrome.tabs.query({ active: true, currentWindow: true });
  state.tab = tab;

  let url;
  try {
    url = tab && tab.url ? new URL(tab.url) : null;
  } catch (_) {
    url = null;
  }
  if (!url || !/^https?:$/.test(url.protocol)) {
    $("site").textContent = tab && tab.url ? tab.url : "No active tab";
    $("count").textContent = "";
    setStatus("Cookies can only be exported from http(s) pages.", true);
    $("copy").disabled = $("download").disabled = true;
    $("format").disabled = $("wholeDomain").disabled = true;
    return;
  }

  state.url = url.href;
  $("site").textContent = url.origin;
  state.storeId = await getStoreIdForTab(tab.id);
  await refresh();
}

init();
